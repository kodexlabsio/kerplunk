def _loglog(xs: list[float], ys: list[float]) -> tuple[float, float]:
    """The slope of a least-squares line through (log x, log y), and its coefficient of
    determination."""
    import math

    lx, ly = [math.log(x) for x in xs], [math.log(max(y, 1e-9)) for y in ys]
    n = len(lx)
    mean_x, mean_y = sum(lx) / n, sum(ly) / n
    sxx = sum((x - mean_x) ** 2 for x in lx)
    sxy = sum((x - mean_x) * (y - mean_y) for x, y in zip(lx, ly, strict=True))
    slope = sxy / sxx if sxx else 0.0
    intercept = mean_y - slope * mean_x
    total = sum((y - mean_y) ** 2 for y in ly)
    residual = sum((y - (intercept + slope * x)) ** 2 for x, y in zip(lx, ly, strict=True))
    return slope, 1 - residual / total if total else 1.0


