class Numbers:
    """The macros the paper uses, with a note on where each came from."""

    def __init__(self, previous: dict[str, dict[str, str]] | None = None) -> None:
        self.values: dict[str, dict[str, str]] = dict(previous or {})
        self.tables: dict[str, str] = {}

    def add(self, name: str, value: Any, note: str) -> None:
        if not re.fullmatch(r'[a-zA-Z]+', name):
            raise ValueError(f'a LaTeX macro name has letters only: {name}')
        self.values[name] = {'value': _format(value), 'note': note}

    def table(self, name: str, rows: list[str]) -> None:
        """Rows for a table, as a macro named after the file (``packs-table`` gives
        ``\\packsTable``): a file read with ``\\input`` inside a tabular breaks its rules."""
        macro = re.sub(r'-([a-z])', lambda m: m.group(1).upper(), name)
        body = '\n'.join(rows)
        self.tables[name] = f'\\newcommand{{\\{macro}}}{{%\n{body}\n}}\n'

    def plot(self, name: str, lines: list[str]) -> None:
        """Plot commands, read with ``\\input`` inside a pgfplots axis."""
        self.tables[name] = '\n'.join(lines) + '\n'

    def write(self, out: Path) -> None:
        out.mkdir(parents=True, exist_ok=True)
        header = '% Generated by paper/generate.py from the runs it describes. Do not edit.\n'
        lines = [header]
        for name in sorted(self.values):
            entry = self.values[name]
            lines.append(f'\\newcommand{{\\{name}}}{{{entry["value"]}}} % {entry["note"]}')
        (out / 'numbers.tex').write_text('\n'.join(lines) + '\n', encoding='utf-8')
        (out / 'numbers.json').write_text(json.dumps(self.values, indent=1, sort_keys=True) + '\n')
        for name, text in self.tables.items():
            (out / f'{name}.tex').write_text(header + text, encoding='utf-8')


def _format(value: Any) -> str:
    if isinstance(value, bool):
        return 'yes' if value else 'no'
    if isinstance(value, int):
        return f'{value:,}'
    if isinstance(value, float):
        return f'{value:,.2f}'.rstrip('0').rstrip('.') if abs(value) < 100 else f'{value:,.0f}'
    return str(value)


def tex(text: str) -> str:
    """Text set in the paper as it is, with LaTeX's special characters escaped."""
    replacements = {
        '\\': r'\textbackslash{}',
        '_': r'\_',
        '%': r'\%',
        '&': r'\&',
        '#': r'\#',
        '$': r'\$',
        '{': r'\{',
        '}': r'\}',
        '~': r'\textasciitilde{}',
        '^': r'\textasciicircum{}',
    }
    return ''.join(replacements.get(c, c) for c in text)


def percent(part: int, whole: int) -> str:
    return f'{100 * part / whole:.0f}' if whole else '100'


def timed(numbers: Numbers, section: str, func: Callable[[Numbers], None]) -> None:
    started = time.perf_counter()
    print(f'paper: {section}', file=sys.stderr, flush=True)
    func(numbers)
    print(f'paper: {section} took {time.perf_counter() - started:.0f} s', file=sys.stderr, flush=True)


