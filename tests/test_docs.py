def test_every_field_of_a_public_result_is_documented() -> None:
    """The API reference documents each field from the docstring under it."""
    missing = []
    for module, names in PUBLIC_RESULTS.items():
        tree = ast.parse((ROOT / 'konstruct' / module).read_text())
        for node in tree.body:
            if not isinstance(node, ast.ClassDef) or node.name not in names:
                continue
            body = node.body
            for i, statement in enumerate(body):
                if not isinstance(statement, ast.AnnAssign) or not isinstance(statement.target, ast.Name):
                    continue
                following = body[i + 1] if i + 1 < len(body) else None
                documented = isinstance(following, ast.Expr) and isinstance(
                    getattr(following, 'value', None), ast.Constant
                )
                if not documented:
                    missing.append(f'{module}:{node.name}.{statement.target.id}')
    assert missing == []


def _features() -> str:
    readme = (ROOT / 'README.md').read_text(encoding='utf-8')
    return readme.split('## Features', 1)[1].split('\n## ', 1)[0]


def _bullet(features: str, start: str) -> str:
    return next(line for line in features.splitlines() if line.startswith(f'- {start}'))


def test_the_readme_lists_every_command_and_format() -> None:
    """The README's feature list names every command, export format, verify warehouse and usage
    warehouse, and only ontology packs that exist."""
    import argparse

    from konstruct.analysis.verify import REMOTE
    from konstruct.inputs.usage import SUPPORTED
    from konstruct.interfaces.cli import parser
    from konstruct.outputs.export import FORMATS
    from konstruct.semantics.registry import load_packs

    features = _features()
    commands = next(a for a in parser()._actions if isinstance(a, argparse._SubParsersAction)).choices
    missing = [c for c in commands if f'`konstruct {c}`' not in features]
    names = {
        'openlineage': 'OpenLineage',
        'mermaid': 'Mermaid',
        'dot': 'Graphviz DOT',
        'csv': 'CSV',
        'ossie': 'Ossie',
    }
    exports = _bullet(features, 'Other tools')
    missing += [f'export {f}' for f in FORMATS if f not in names or names[f] not in exports]
    titles = {'bigquery': 'BigQuery'}
    verify = _bullet(features, '`konstruct verify`')
    missing += [f'verify on {w}' for w in REMOTE if titles.get(w, w.capitalize()) not in verify]
    usage = _bullet(features, 'Column usage')
    missing += [f'usage from {w}' for w in SUPPORTED if titles.get(w, w.capitalize()) not in usage]
    assert not missing
    from konstruct.semantics.registry import PACKS

    every = {p.name for p in load_packs()}
    packs = _bullet(features, f'{len(every)} ontology packs')
    listed = packs.split(', from ', 1)[1].split(', bound')[0].replace(' to ', ', ').replace(' and ', ', ')
    named = [n.lower().replace(' ', '_') for n in listed.split(', ')]
    # The README gives the number of packs, every pack it names exists, and it names every
    # hand-written pack.
    assert set(named) <= every, named
    assert {path.stem for path in PACKS.glob('*.yml')} <= set(named), named


@pytest.mark.dbt
def test_the_readme_lists_every_mcp_tool(jaffle_built_graph: Path) -> None:
    import anyio
    from mcp import Client

    from konstruct.interfaces.mcp_server import build_server

    async def names() -> list[str]:
        async with Client(build_server(jaffle_built_graph)) as client:
            return [t.name for t in (await client.list_tools()).tools]

    tools = anyio.run(names)
    listed = _bullet(_features(), 'Coding agents')
    assert tools and [t for t in tools if f'`{t}`' not in listed] == []


def test_the_citation_agrees_with_the_package_metadata() -> None:
    # CITATION.cff is checked against the CFF 1.2.0 schema by cffconvert in CI; this keeps it in
    # step with pyproject.toml. It carries no version or release date, which would go stale.
    citation = yaml.safe_load((ROOT / 'CITATION.cff').read_text())
    project = tomllib.loads((ROOT / 'pyproject.toml').read_text())['project']
    assert citation['cff-version'] == '1.2.0'
    assert citation['title'].lower() == project['name']
    assert ' '.join(citation['abstract'].split()) == project['description']
    assert citation['authors'] == [{'name': author['name']} for author in project['authors']]
    # CFF takes the licences as a list of SPDX identifiers; the package joins the same ones with AND.
    assert citation['license'] == project['license'].split(' AND ')
    assert citation['repository-code'] == project['urls']['Homepage']
    assert citation['keywords'] == project['keywords']
    assert 'version' not in citation and 'date-released' not in citation
