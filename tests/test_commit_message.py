from __future__ import annotations

import importlib.util
import sys
from pathlib import Path
from types import ModuleType

import pytest

SCRIPT = Path(__file__).resolve().parents[1] / '.kodex' / 'scripts' / 'check_commit_message.py'


def _load() -> ModuleType:
    spec = importlib.util.spec_from_file_location('check_commit_message', SCRIPT)
    assert spec and spec.loader
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


ccm = _load()


@pytest.mark.parametrize(
    'message',
    [
        'feat(dbt): Parse the manifest',
        'fix: Handle an empty catalog',
        'feat(mcp)!: Rename the impact tool',
        'chore(deps-dev): Bump ruff',
        'docs(readme): Add the type mapping table\n\nThe body explains why.\n',
        'feat(sql): Add MCP lineage\n\n# Please enter the commit message\n',
        "Merge branch 'main' into feature",
        'feat(cli): Add build\n\n# ------------------------ >8 ------------------------\ndiff --git Generated by Claude',
    ],
)
def test_accepts(message: str) -> None:
    assert ccm.check(message) == []


@pytest.mark.parametrize(
    ('message', 'fragment'),
    [
        ('added stuff', 'type(scope): Subject'),
        ('feature(dbt): Add x', "type 'feature'"),
        ('feat(website): Add x', "scope 'website'"),
        ('feat(DBT): Add x', 'lower case'),
        ('feat(dbt): add x', 'sentence case'),
        ('feat(dbt): MCP server', 'sentence case'),
        ('feat(dbt): Add x.', 'full stop'),
        ('feat(dbt): ', 'subject is empty'),
        ('feat(dbt): Add x\nbody straight away', 'blank line'),
        ('feat(dbt): ' + 'A' * 100, 'header is longer'),
        ('feat(dbt): Add x\n\n' + 'word ' * 30, 'line 3 is longer'),
        ('feat(dbt): Add x\n\nCo-Authored-By: Claude Opus <noreply@anthropic.com>', 'AI attribution'),
        ('feat(dbt): Add x\n\nGenerated with Claude Code', 'AI attribution'),
        ('feat(dbt): Add x\n\n\U0001f916 Generated', 'AI attribution'),
        ('feat(dbt): Add x\n\nAssisted-by: anything', 'AI attribution'),
        ('', 'empty'),
        ('feat(cli): Add x\n\nUseful for the investor deck.', 'business'),
        ('docs(readme): Explain the pricing tiers', 'business'),
        ('feat(mcp): Add x\n\nThis grows ARR.', 'business'),
        ('chore: Prepare the seed fundraise', 'business'),
        ('docs: Note the VC feedback', 'business'),
    ],
)
def test_rejects(message: str, fragment: str) -> None:
    errors = ccm.check(message)
    assert any(fragment in error for error in errors), errors


@pytest.mark.parametrize(
    'message',
    [
        'feat(sql): Parse the arrangement of window frames',
        'fix(dbt): Read the tam_score column',
        'feat(cli): Price nothing, compute everything',
        'fix(warehouse): Handle an empty VARCHAR column',
    ],
)
def test_business_words_need_whole_words(message: str) -> None:
    assert ccm.check(message) == []


def test_human_co_author_is_allowed() -> None:
    assert ccm.check('feat(dbt): Add x\n\nCo-authored-by: Sam Smith <sam@example.com>') == []


def test_main_reads_a_message_file(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    good = tmp_path / 'good'
    good.write_text('feat(cli): Add the build command\n')
    bad = tmp_path / 'bad'
    bad.write_text('feat(cli): add the build command\n')
    assert ccm.main([str(good)]) == 0
    assert ccm.main([str(bad)]) == 1
    assert 'sentence case' in capsys.readouterr().err
